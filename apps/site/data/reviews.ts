import { CLINIC } from '@/lib/clinic'

export interface Review {
  id: string
  /** Имя как его оставил автор. Фамилию целиком не публикуем. */
  author: string
  /** Роль: сам пациент или родственник — читателю это важно. */
  relation: string
  rating: number
  date: string
  text: string
}

/**
 * Отзывы.
 *
 * Список пустой НАМЕРЕННО, и заполнять его выдуманными текстами нельзя:
 *
 * 1. Отзыв принадлежит автору. Перенос чужого текста с 2ГИС на
 *    коммерческий сайт без разрешения — нарушение, а в медицине ещё и
 *    репутационный риск: человек может потребовать убрать упоминание
 *    своего лечения.
 * 2. Придумывать отзывы за клинику нельзя вообще никогда.
 *
 * Раньше здесь лежали три карточки с текстом «[ТЕКСТ ОТЗЫВА]» — они
 * доезжали до посетителя. Пока настоящих отзывов нет, блок показывает
 * проверяемый рейтинг и ссылку на первоисточник.
 *
 * Правильных путей два:
 *   — официальный виджет отзывов 2ГИС (тянет реальные отзывы с их
 *     стороны, ничего копировать не нужно);
 *   — собственные отзывы, собранные клиникой с письменного согласия.
 */
export const REVIEWS: Review[] = []

